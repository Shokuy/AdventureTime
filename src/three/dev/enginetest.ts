import * as THREE from 'three';
import { Renderer3D } from '../render';
import { TPCamera } from '../camera';
import { PhysWorld, makeBody } from '../physics/world';
import { mat, mesh } from '../gfx';
import { FX3 } from '../fx';
import { input } from '../../engine/input';

const canvas = document.getElementById('c') as HTMLCanvasElement;
const r = new Renderer3D(canvas);
const resize = () => r.setSize(innerWidth, innerHeight, devicePixelRatio);
resize(); addEventListener('resize', resize);
input.setMode('3d');
input.attach(canvas, (x, y) => [x, y]);
const scene = new THREE.Scene();
scene.background = new THREE.Color('#3a2216');
scene.fog = new THREE.Fog('#3a2216', 40, 120);
scene.add(new THREE.HemisphereLight('#ffe2bc', '#5a3420', 1.2));
const sun = new THREE.DirectionalLight('#ffd9a0', 2.2); sun.position.set(20, 40, 25); sun.castShadow = true; sun.shadow.mapSize.set(2048, 2048);
Object.assign(sun.shadow.camera, { left: -30, right: 30, top: 30, bottom: -30 });
scene.add(sun);
const phys = new PhysWorld();
const box = (x: number, y: number, z: number, w: number, h: number, d: number, c: string) => {
  const m = mesh(new THREE.BoxGeometry(w, h, d), mat(c)); m.position.set(x, y + h / 2, z); scene.add(m);
  phys.add({ kind: 'box', min: new THREE.Vector3(x - w / 2, y, z - d / 2), max: new THREE.Vector3(x + w / 2, y + h, z + d / 2) });
};
box(0, -1, 0, 80, 1, 80, '#a8703f');
box(4, 0, -4, 3, 1.6, 3, '#c08a50');
box(8, 0, -6, 3, 3.2, 3, '#c0392b');
box(-6, 0, -8, 6, 8, 6, '#2e86c1');
const jar = mesh(new THREE.CylinderGeometry(2, 2, 7, 32), mat('#c8203a')); jar.position.set(-4, 3.5, 6); scene.add(jar);
phys.add({ kind: 'cyl', x: -4, z: 6, r: 2, y0: 0, y1: 7 });
const hero = new THREE.Group();
const body = mesh(new THREE.CapsuleGeometry(0.28, 0.4, 4, 12), mat('#3fb8a8')); body.position.y = 0.48; hero.add(body);
const head = mesh(new THREE.SphereGeometry(0.26, 24, 16), mat('#ffd9b3')); head.position.y = 0.95; hero.add(head);
const hat = mesh(new THREE.SphereGeometry(0.27, 24, 12, 0, Math.PI * 2, 0, Math.PI / 2), mat('#ff8a2a')); hat.position.y = 0.98; hero.add(hat);
scene.add(hero);
const fx = new FX3(); scene.add(fx.group);
const b = makeBody(0.3, 0.95);
b.pos.set(0, 0, 8);
const tc = new TPCamera();
tc.snap(b.pos);
let last = performance.now();
function frame(now: number) {
  const dt = Math.min(0.05, (now - last) / 1000); last = now;
  input.beginTick();
  if (input.mouseClicked) input.requestLock();
  const m = input.move3(); const { f, r: rr } = tc.basis();
  b.vel.x = (rr.x * m.x + f.x * m.y) * 7.6; b.vel.z = (rr.y * m.x + f.y * m.y) * 7.6;
  if (input.pressed('jump') && b.onGround) b.vel.y = 11.6;
  phys.move(b, dt);
  if (b.onGround && Math.hypot(b.vel.x, b.vel.z) > 1 && Math.random() < 0.3) fx.dust(b.pos.clone(), 1);
  hero.position.copy(b.pos);
  if (Math.hypot(b.vel.x, b.vel.z) > 0.1) hero.rotation.y = Math.atan2(b.vel.x, b.vel.z);
  fx.update(dt);
  tc.setAspect(innerWidth / innerHeight);
  tc.update(dt, b.pos, b.vel, phys, true);
  sun.position.copy(b.pos).add(new THREE.Vector3(20, 40, 25)); sun.target.position.copy(b.pos); sun.target.updateMatrixWorld();
  fx.setScale(innerHeight * r.pixelRatio * 0.9);
  r.render(scene, tc.cam);
  input.endTick();
  requestAnimationFrame(frame);
}
requestAnimationFrame(frame);
(window as unknown as Record<string, unknown>).__t = { b, tc, r };
